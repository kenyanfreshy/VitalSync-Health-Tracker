/**
 * Look up the indication for a medication name.
 * Performs a case-insensitive exact match first, then a prefix match.
 * Returns null if no match is found.
 */
export function lookupIndication(name: string): string | null {
  if (!name || name.trim().length < 3) return null;
  const lower = name.trim().toLowerCase();
  // Exact match
  if (INDICATION_LOOKUP[lower]) return INDICATION_LOOKUP[lower];
  // Prefix match (e.g. "Lisinopril 10mg" → "lisinopril")
  for (const key of Object.keys(INDICATION_LOOKUP)) {
    if (lower.startsWith(key) || key.startsWith(lower)) {
      return INDICATION_LOOKUP[key];
    }
  }
  return null;
}
